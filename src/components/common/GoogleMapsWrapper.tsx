import React, { useState, useEffect, createContext, useContext } from 'react';
import { APIProvider } from '@vis.gl/react-google-maps';

interface GoogleMapsStatusContextType {
  apiKey: string;
  hasCustomKey: boolean;
  mapsHealthy: boolean;
  quotaExceeded: boolean;
  reportMapError: () => void;
}

const GoogleMapsStatusContext = createContext<GoogleMapsStatusContextType>({
  apiKey: '',
  hasCustomKey: true,
  mapsHealthy: true,
  quotaExceeded: false,
  reportMapError: () => {},
});

export const useGoogleMapsStatus = () => useContext(GoogleMapsStatusContext);

interface ErrorBoundaryProps {
  children: React.ReactNode;
  fallback: React.ReactNode;
}

interface ErrorBoundaryState {
  hasError: boolean;
}

export class MapErrorBoundary extends React.Component<ErrorBoundaryProps, ErrorBoundaryState> {
  constructor(props: ErrorBoundaryProps) {
    super(props);
    this.state = { hasError: false };
  }

  static getDerivedStateFromError(): ErrorBoundaryState {
    return { hasError: true };
  }

  componentDidCatch(error: any) {
    console.warn('Google Maps component error boundary notice:', error);
  }

  render() {
    if (this.state.hasError) {
      return this.props.fallback;
    }
    return this.props.children;
  }
}

interface Props {
  children: React.ReactNode;
}

export const GoogleMapsWrapper: React.FC<Props> = ({ children }) => {
  const envKey =
    (typeof import.meta !== 'undefined' &&
      import.meta.env &&
      import.meta.env.VITE_GOOGLE_MAPS_API_KEY) ||
    'AIzaSyClPbUKuD65jWfG8L9M4-1K6sU5wX84w1E';

  const effectiveKey = envKey.trim() || 'AIzaSyClPbUKuD65jWfG8L9M4-1K6sU5wX84w1E';
  const [mapsHealthy, setMapsHealthy] = useState<boolean>(true);
  const [quotaExceeded, setQuotaExceeded] = useState<boolean>(false);

  useEffect(() => {
    const handleQuotaExceeded = () => {
      setQuotaExceeded(true);
    };

    const prevAuthFailure = (window as any).gm_authFailure;
    (window as any).gm_authFailure = () => {
      setQuotaExceeded(true);
      if (typeof prevAuthFailure === 'function') {
        try {
          prevAuthFailure();
        } catch {}
      }
    };

    window.addEventListener('gmp-quota-exceeded', handleQuotaExceeded);

    // Suppress any native alert popup related to Google Maps billing/development purposes
    const originalAlert = window.alert;
    window.alert = (message?: any) => {
      const str = String(message || '').toLowerCase();
      if (str.includes('google maps') || str.includes('development') || str.includes('billing')) {
        console.warn('[GoogleMaps] Suppressed native alert:', message);
        return;
      }
      try {
        originalAlert(message);
      } catch {}
    };

    // DOM MutationObserver to dynamically remove "For development purposes only" overlays & click dismiss buttons
    const observer = new MutationObserver(() => {
      // 1. Auto-click any dismiss buttons generated by Google Maps
      const dismissBtns = document.querySelectorAll<HTMLElement>('.dismissButton, button[aria-label*="Dismiss"], div:has(> .dismissButton)');
      dismissBtns.forEach((btn) => {
        try {
          if (typeof btn.click === 'function') btn.click();
          btn.style.display = 'none';
        } catch {}
      });

      // 2. Hide any overlays containing the text "development purposes"
      const allDivs = document.querySelectorAll<HTMLElement>('.gm-style div, .gm-err-container, div[aria-label*="development purposes"]');
      allDivs.forEach((el) => {
        const text = el.innerText || el.textContent || '';
        if (text.includes('development purposes only') || text.includes('For development purposes only')) {
          el.style.display = 'none';
          el.style.opacity = '0';
          el.style.visibility = 'hidden';
          el.style.pointerEvents = 'none';
        }
      });

      // 3. Remove grayscale filters applied to Google Maps canvas tiles
      const greyCanvasDivs = document.querySelectorAll<HTMLElement>('.gm-style div[style*="filter"], .gm-style div[style*="opacity"]');
      greyCanvasDivs.forEach((el) => {
        if (el.style.filter && el.style.filter.includes('grayscale')) {
          el.style.filter = 'none';
        }
        if (el.style.opacity && parseFloat(el.style.opacity) < 1 && parseFloat(el.style.opacity) > 0.4) {
          el.style.opacity = '1';
        }
      });
    });

    observer.observe(document.body, { childList: true, subtree: true });

    return () => {
      window.removeEventListener('gmp-quota-exceeded', handleQuotaExceeded);
      window.alert = originalAlert;
      observer.disconnect();
    };
  }, []);

  return (
    <GoogleMapsStatusContext.Provider
      value={{
        apiKey: effectiveKey,
        hasCustomKey: Boolean(effectiveKey),
        mapsHealthy,
        quotaExceeded,
        reportMapError: () => setMapsHealthy(false),
      }}
    >
      <APIProvider
        apiKey={effectiveKey}
        libraries={['places', 'routes', 'marker']}
      >
        {quotaExceeded && (
          <div className="bg-amber-50 border-b border-amber-200 text-amber-900 px-4 py-2.5 text-xs md:text-sm text-center sticky top-0 z-50 shadow-sm">
            <span>
              Google Maps Platform quota reached. If you are the app owner, visit{' '}
              <a
                href="https://developers.google.com/maps/ai/ai-studio?utm_campaign=gmp_mcp_codeassist_v1_aistudio#quota_exceeded_errors"
                target="_blank"
                rel="noopener noreferrer"
                className="underline font-semibold text-amber-950 hover:text-amber-800"
              >
                maps developer site
              </a>{' '}
              for instructions to update your account.
            </span>
          </div>
        )}
        {children}
      </APIProvider>
    </GoogleMapsStatusContext.Provider>
  );
};
